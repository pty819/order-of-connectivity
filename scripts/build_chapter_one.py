#!/usr/bin/env python3
"""Assemble the edited chapter frame and 75 manuscripts into one reading copy.

The independent manuscripts remain canonical. This checks assembly and source
relationships, not historical accuracy, sufficiency, or publication readiness.
"""
import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CHAPTER = ROOT / "book/chapters/01-scarcity"
FOOTNOTE = re.compile(r"^\[\^(R\d{4})\]:.*$", re.M)


def read_csv(path):
    with (ROOT / path).open(encoding="utf-8", newline="") as stream:
        return list(csv.DictReader(stream))


def body(text):
    return FOOTNOTE.sub("", text).rstrip()


def build():
    manifest = read_csv("research/chapter-01-subtopics.csv")
    sections = {row["id"]: row for row in read_csv("research/section-outline-v1.csv")}
    refs = {row["id"]: row for row in read_csv("references/references.csv")}
    if len(manifest) != 75 or any(row["status"] not in {"research_draft", "revised_draft"} for row in manifest):
        raise ValueError("All 75 independent research drafts must exist before assembly")
    chunks = []
    previous = None
    for row in manifest:
        section = sections[row["section_id"]]
        number = section["section_order"]
        if row["section_id"] != previous:
            chunks.append(f"## 1.{number}　{section['title']}")
            previous = row["section_id"]
        source = (ROOT / row["manuscript"]).read_text(encoding="utf-8")
        if source.splitlines()[0] != "# " + row["title"]:
            raise ValueError(f"Title drift: {row['id']}")
        source = body(source).split("\n", 1)[1].lstrip()
        source = re.sub(r"\A第一章·1\.\d+\.\d+。", "", source)
        source = re.sub(r"^(#{2,}) ", lambda match: "##" + match[1] + " ", source, flags=re.M)
        chunks.append(f"### 1.{number}.{row['subtopic_order']}　{row['title']}\n\n{source}")
    frame = body((CHAPTER / "chapter-frame.md").read_text(encoding="utf-8"))
    marker = "<!-- CHAPTER BODY -->"
    if frame.count(marker) != 1:
        raise ValueError("Expected one chapter body insertion point")
    text = frame.replace(marker, "\n\n".join(chunks))
    rewritten = sum(row["status"] == "revised_draft" for row in manifest)
    progress = f"> 论述重写中：{rewritten}/75篇已作本轮改写；其余{75-rewritten}篇仍为待重写的史料型底稿。全章尚未完成论述修订。"
    text = text.replace("# 第一章：稀缺的连接\n", "# 第一章：稀缺的连接\n\n" + progress + "\n", 1)
    cited = sorted(set(re.findall(r"\[\^(R\d{4})\](?!:)", text)))
    notes = []
    for rid in cited:
        ref = refs[rid]
        note = f"{ref['creator']}，[{ref['title']}]({ref['url']})。定位：{ref['locator']}。阅读与限制：{ref['notes']}"
        notes.append(f"[^{rid}]: {note}")
    header = "<!-- Generated by scripts/build_chapter_one.py; edit chapter-frame.md or subtopics/*.md. -->\n\n"
    text = header + text + "\n\n## 全章注释与阅读范围\n\n" + "\n".join(notes) + "\n"
    (CHAPTER / "manuscript.md").write_text(text, encoding="utf-8")
    assert text.count("### 1.") == len(manifest)
    assert set(FOOTNOTE.findall(text)) == set(cited)
    print(f"Assembled {len(manifest)} drafts, 15 sections, {len(cited)} chapter references.")


if __name__ == "__main__":
    build()
