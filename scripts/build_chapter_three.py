#!/usr/bin/env python3
"""Assemble chapter three without turning planned topics into empty manuscripts."""
import csv
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CHAPTER = ROOT / 'book/chapters/03-internet'


def rows(path):
    with (ROOT / path).open(encoding='utf-8', newline='') as stream:
        return list(csv.DictReader(stream))


def main():
    topics = rows('research/chapter-03-subtopics.csv')
    sections = sorted((s for s in rows('research/section-outline-v1.csv') if s['chapter_id'] == 'CH03'),
                      key=lambda s: int(s['section_order']))
    refs = {r['id']: r for r in rows('references/references.csv')}
    reviews = {r['id']: r for r in rows('research/chapter-03-topic-review.csv')}
    state = json.loads((ROOT / 'research/chapter-03-editorial-status.json').read_text())
    ready = sum(t['status'] != 'planned' for t in topics)
    expected = {s['id'] + f'-T{i:02d}' for s in sections for i, _ in enumerate(s['subtopics'].split(';'), 1)}
    assert len(topics) == len(expected) and {t['id'] for t in topics} == expected
    assert state['topics_written'] == ready and state['topics_planned'] == len(topics) - ready
    progress = (f'编纂中：{len(sections)}节、{len(topics)}个计划话题；{ready}篇论述初稿，'
                f'{len(topics)-ready}篇待写，{state["topics_reviewed"]}篇完成本轮实质审读。'
                '全章整合及完成审计尚未完成。')
    title = '# 第三章：互联网的拓荒——科研联网到公众接入'
    links = ('[编纂与取材方案](../../../research/chapter-03-writing-plan.md) · '
             '[逐题清单](../../../research/chapter-03-subtopics.csv) · '
             '[首批论证材料组合](../../../research/chapter-03-evidence-bundles.csv)')
    intro = [title, '', progress, '',
             '以1987—2003年为重心，后续宽带转型另标时期。以较长期的科研、通信与社会条件，'
             '中期的制度和市场变化，以及可定位的事件相互解释。连续统计与同期过程材料共同检验论点，'
             '同源转载不重复计算为独立佐证；题目齐全与引文数量不构成完成证明。', '', links, '']
    index = intro + ['[当前连续阅读稿](manuscript.md)', '', '## 逐题入口', '']
    reader = ['<!-- Generated by scripts/build_chapter_three.py; edit subtopics/*.md. -->', ''] + intro
    for section in sections:
        heading = f"3.{section['section_order']}　{section['title']}"
        index += ['## ' + heading, '', section['question'], '']
        passages = []
        for topic in (t for t in topics if t['section_id'] == section['id']):
            label = f"3.{section['section_order']}.{topic['subtopic_order']}　{topic['title']}"
            path = ROOT / topic['manuscript']
            if topic['status'] == 'planned':
                assert not path.exists(), topic['id']
                index.append('- ' + label + '（待取材与撰写）')
                continue
            text = path.read_text()
            assert text.splitlines()[0] == '# ' + topic['title']
            stage = '首批实质审读完成，待全章整合与补证' if reviews[topic['id']]['review_status'] == 'reviewed' else '论述初稿，待实质审读'
            index.append(f'- [{label}](subtopics/{path.name})（{stage}）')
            passage = re.sub(r'^\[\^R\d{4}\]:.*$', '', text, flags=re.M).rstrip().split('\n', 1)[1].lstrip()
            passage = re.sub(r'\A第三章·3\.\d+\.\d+。', '', passage)
            passage = re.sub(r'^(#{2,}) ', lambda m: '##' + m[1] + ' ', passage, flags=re.M)
            passages += ['### ' + label, '', passage, '']
        index.append('')
        if passages:
            reader += ['## ' + heading, ''] + passages
    reader += ['## 当前引用与实际阅读范围', '']
    uses = sorted(set(re.findall(r'\[\^(R\d{4})\](?!:)', '\n'.join(reader))))
    for rid in uses:
        r = refs[rid]
        reader.append(f"[^{rid}]: {r['creator']}，[{r['title']}]({r['url']})。定位：{r['locator']}。阅读与限制：{r['notes']}")
    CHAPTER.mkdir(parents=True, exist_ok=True)
    (CHAPTER / 'README.md').write_text('\n'.join(index) + '\n')
    (CHAPTER / 'manuscript.md').write_text('\n'.join(reader) + '\n')
    print(f'Chapter three: {ready}/{len(topics)} topic bodies, {len(uses)} cited source units; in progress.')


if __name__ == '__main__':
    main()
