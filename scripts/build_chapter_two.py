#!/usr/bin/env python3
"""Assemble chapter two and its recorded editorial state; not certify historical quality."""
import csv
import json
import re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
CHAPTER=ROOT/'book/chapters/02-restructuring'
def read(path):
 with (ROOT/path).open(encoding='utf-8',newline='') as f:return list(csv.DictReader(f))
def main():
 topics=read('research/chapter-02-subtopics.csv')
 sections=sorted((s for s in read('research/section-outline-v1.csv') if s['chapter_id']=='CH02'),key=lambda s:int(s['section_order']))
 refs={r['id']:r for r in read('references/references.csv')}
 expected={f"{s['id']}-T{i:02d}" for s in sections for i,_ in enumerate(s['subtopics'].split(';'),1)}
 if set(t['id'] for t in topics)!=expected:raise ValueError('Chapter-two outline scope changed')
 ready=sum(t['status']=='revised_draft' for t in topics)
 audit_path=ROOT/'research/chapter-02-integrated-audit.csv'
 audits={r['id']:r for r in read('research/chapter-02-integrated-audit.csv')} if audit_path.exists() else {}
 reviewed=sum(r['review_status']=='reviewed' for r in audits.values())
 state_path=ROOT/'research/chapter-02-editorial-status.json'
 state=json.loads(state_path.read_text(encoding='utf-8')) if state_path.exists() else {}
 finished=all(state.get(stage)=='complete' for stage in ('argument_drafting','topic_review','chapter_integration','completion_audit'))
 deepening=state.get('depth_revision')=='in_progress'
 progress=(f'本轮内部论述修订已完成：17节、{len(topics)}篇独立正文，逐篇实读与整章整合的完成依据见[完成审计](../../../research/chapter-02-completion-audit.md)。仍为研究初稿，保留原始材料未解项，未作外部学术审稿。' if finished else
           f'编纂中：17节、{len(topics)}个独立话题；{ready}篇已有论述初稿，{len(topics)-ready}篇待写。本轮逐篇实质审读已落实{reviewed}/{len(topics)}篇；正在整章编辑，正文齐全不代表整章完成。')
 if deepening:
  progress=(f'论证深化中：17节、{len(topics)}篇既有正文；首轮修订已保存，本次依用户意见重新检查话题充分性与解释深度，已扩写{state.get("depth_revised_topics",0)}篇。'
            '现有篇目不作为内容上限，不以约两千字限制复杂问题。[深度复查与逐节补写](../../../research/chapter-02-depth-review.md)记录当前工作；尚未宣布本次深化完成。')
 intro=['# 第二章：拆分与重组——谁有权经营全国网络','',
 '以1994—2008年为重心，研究经营资格、资产、人员、债务和共同网络如何被重新组织。改革不只改变公司数量，还改变谁能够使用什么投入、向谁承担什么责任。前史与后续观察分别标明，不用后来三家格局筛掉曾经存在的道路。','',
 progress,'',
 '[编纂方案与边界](../../../research/chapter-02-writing-plan.md) · [逐题清单](../../../research/chapter-02-subtopics.csv) · [当前连续阅读稿](manuscript.md)','']
 index=intro+['## 逐题入口','']
 frame_path=CHAPTER/'chapter-frame.md'
 frame_end=''
 header='<!-- Generated by scripts/build_chapter_two.py; edit chapter-frame.md or subtopics/*.md. -->'
 if frame_path.exists():
  if ready!=len(topics):raise ValueError('A formal chapter frame requires all topic bodies')
  frame=re.sub(r'^\[\^R\d{4}\]:.*$','',frame_path.read_text(encoding='utf-8'),flags=re.M).rstrip()
  if frame.count('<!-- CHAPTER BODY -->')!=1:raise ValueError('Expected one chapter insertion marker')
  frame_start,frame_end=frame.split('<!-- CHAPTER BODY -->')
  if not frame_start.startswith(intro[0]+'\n') or '## 章末：' not in frame_end:raise ValueError('Missing chapter opening or ending')
  frame_start=frame_start.replace(intro[0]+'\n',intro[0]+'\n\n> '+progress+'\n',1)
  reader=[header,'',frame_start.strip(),'']
 else:
  if finished:raise ValueError('A completed chapter requires its formal frame')
  reader=[header,'',intro[0],'',progress,'',f'当前汇集{ready}篇正文；正式章首章末尚待编写。','']
 for s in sections:
  title=f"2.{s['section_order']}　{s['title']}";index += ['## '+title,'',s['question'],'']
  written=[]
  for t in (t for t in topics if t['section_id']==s['id']):
   label=f"2.{s['section_order']}.{t['subtopic_order']}　{t['title']}";p=ROOT/t['manuscript']
   if t['status']=='planned':index.append(f'- {label}（待写）');continue
   text=p.read_text(encoding='utf-8');assert text.splitlines()[0]=='# '+t['title']
   label_state='研究初稿，本轮内部修订完成' if finished else ('已作本轮逐篇实读修订' if audits.get(t['id'],{}).get('review_status')=='reviewed' else '论述初稿，待实质审读')
   if deepening:label_state='研究初稿，继续深化中'
   index.append(f"- [{label}](subtopics/{p.name})（{label_state}）")
   body=re.sub(r'^\[\^R\d{4}\]:.*$','',text,flags=re.M).rstrip().split('\n',1)[1].lstrip()
   body=re.sub(r'\A第二章·2\.\d+\.\d+。','',body)
   body=re.sub(r'^(#{2,}) ',lambda m:'##'+m[1]+' ',body,flags=re.M)
   written += ['### '+label,'',body,'']
  index.append('')
  if written:reader += ['## '+title,'']+written
 if frame_end:reader += [frame_end.strip(),'']
 cited=sorted(set(re.findall(r'\[\^(R\d{4})\](?!:)', '\n'.join(reader))))
 reader += ['## 全章注释与阅读范围','']
 for rid in cited:
  r=refs[rid];reader.append(f"[^{rid}]: {r['creator']}，[{r['title']}]({r['url']})。定位：{r['locator']}。阅读与限制：{r['notes']}")
 (CHAPTER/'README.md').write_text('\n'.join(index)+'\n',encoding='utf-8')
 (CHAPTER/'manuscript.md').write_text('\n'.join(reader)+'\n',encoding='utf-8')
 print(f'Chapter two: {ready}/{len(topics)} bodies, {reviewed}/{len(topics)} first-pass review records; integration={state.get("chapter_integration","pending")}. Assembly checks do not certify quality.')
if __name__=='__main__':main()
